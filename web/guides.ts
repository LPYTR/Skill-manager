const templates: Record<string,string> = {
  'analytics-dashboard':'数据分析仪表盘', 'business-review':'业务回顾演示', 'design-report':'设计报告', 'experiment-analysis':'实验分析报告', 'financial-budget':'财务预算表', 'investment-committee-memo':'投资委员会备忘录', 'legal-memorandum':'法律备忘录', 'market-trends-report':'市场趋势演示', 'minimal-letterhead':'简洁商务信函', 'operating-calendar':'运营日历', 'operating-review':'运营回顾演示', 'project-kickoff':'项目启动演示', 'project-tracker':'项目进度跟踪表', 'sales-pipeline':'销售管线表', 'simple-dark-mode':'简洁深色演示', 'simple-light-mode':'简洁浅色演示', 'strategy-memorandum':'战略备忘录', 'system-design':'系统设计文档', 'team-alignment':'团队共识演示', 'three-statement-forecast':'三大财务报表预测',
};
export interface Guide { description: string; task: string; prompt: string; preparation: string; reviewed: boolean }
export function guideFor(skill: Pick<Skill, 'name' | 'description' | 'metadata'>): Guide {
  const name = skill.name.toLowerCase();
  const template = templates[name.replace(/^artifact-template-/, '')];
  const entry = catalog[name] || (name.startsWith('artifact-template-') && template ? [`使用保留的模板制作${template}，保持统一的布局与格式。`, `根据我提供的材料，使用模板制作${template}。`] : undefined);
  // New, unknown packages remain honest: do not guess a translation from their name.
  const chinese = /[\u4e00-\u9fff]/.test(skill.description);
  const description = entry?.[0] || (chinese ? skill.description : '这项技能尚未补充中文用途，请先让 AI 阅读原始说明并解释适用范围。');
  const task = entry?.[1] || (chinese ? `希望使用这项能力时，提供你的目标和相关材料，让 AI 先核对下方原始说明。` : '先确认原始说明中的用途、限制和依赖，再决定是否使用。');
  let preparation = entry?.[2] || '准备具体目标、相关文件或项目，以及你希望得到的结果；AI 会按技能原始说明检查所需依赖。';
  if (name.startsWith('figma-')) preparation = '准备 Figma 文件或节点链接、设计目标与修改范围，并在 AI 工具中连接 Figma 插件。';
  if (['maintain-space','manage-schedules','organize-space','write-page'].includes(name)) preparation = '提供 Page 或 Space 链接、内容材料和修改范围，并连接对应的 Pages 工具。';
  const prompt = entry ? `请使用「${skill.name}」技能。\n${task}\n\n我的具体目标和材料：\n[在这里补充]` : `请先读取「${skill.name}」的 SKILL.md，用中文解释它的用途、调用步骤和依赖。确认适合后，再根据我的目标执行。\n\n我的目标和材料：\n[在这里补充]`;
  return { description, task, prompt, preparation, reviewed: !!entry || chinese };
}
